WITH category_summary AS (
  SELECT
    c.CategoryID,
    c.CategoryName,
    AVG(v.Discount) AS AvgDiscount,
    SUM(v.Revenue) AS TotalRevenue,
    SUM(v.Quantity) AS TotalQuantity,
    SUM(v.Quantity * v.Price) - SUM(v.TotalPrice) AS RevenueLeakage
  FROM `sales-of-fmcg-stores.salesfmcg.vw_sales_analysis` v
  JOIN `sales-of-fmcg-stores.salesfmcg.products` p
    ON v.ProductID = p.ProductID
  JOIN `sales-of-fmcg-stores.salesfmcg.categories` c
    ON p.CategoryID = c.CategoryID
  GROUP BY
    c.CategoryID,
    c.CategoryName
)

SELECT
  *,
  TotalRevenue / SUM(TotalRevenue) OVER () AS RevenueShare
FROM category_summary
ORDER BY AvgDiscount DESC;
-- =========================================================
-- 2.3 PRODUCT CLASS PERFORMANCE
-- Grain: Class
-- =========================================================

SELECT
    p.Class,

    COUNT(DISTINCT p.ProductID) AS TotalProducts,

    SUM(s.Quantity) AS TotalQuantitySold,

    ROUND(SUM(s.Revenue), 2) AS TotalRevenue,

    ROUND(
        SAFE_DIVIDE(
            SUM(s.Revenue),
            COUNT(DISTINCT p.ProductID)
        ),
        2
    ) AS AverageRevenuePerProduct,

    ROUND(
        SAFE_DIVIDE(
            SUM(s.Quantity),
            COUNT(DISTINCT p.ProductID)
        ),
        2
    ) AS AverageQuantityPerProduct

FROM `sales-of-fmcg-stores.salesfmcg.vw_sales_analysis` AS s

JOIN `sales-of-fmcg-stores.salesfmcg.products` AS p
    ON s.ProductID = p.ProductID

GROUP BY p.Class

ORDER BY TotalRevenue DESC;